-- Cada passagem de uma lavadora devolvida pela loja vira uma jornada própria.
-- A OS permanece única e todo o histórico técnico anterior é preservado.

create table if not exists public.linha_branca_lavadora_retornos_loja (
  id bigint generated by default as identity primary key,
  os_id bigint not null references public.ordens_servico(id) on delete cascade,
  numero_retorno integer not null,
  status text not null default 'aberto'
    check (status in ('aberto', 'finalizado', 'encerrado_por_novo_retorno')),
  motivo text not null,
  observacoes text,
  recebido_por text,
  recebido_por_id uuid references auth.users(id) on delete set null,
  recebido_em timestamptz not null default now(),
  finalizado_em timestamptz,
  snapshot_anterior jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (os_id, numero_retorno)
);

create index if not exists idx_lavadora_retornos_os
  on public.linha_branca_lavadora_retornos_loja(os_id, numero_retorno desc);
create index if not exists idx_lavadora_retornos_abertos
  on public.linha_branca_lavadora_retornos_loja(os_id)
  where status = 'aberto';

alter table public.linha_branca_lavadora_retornos_loja enable row level security;
drop policy if exists linha_branca_lavadora_retornos_select on public.linha_branca_lavadora_retornos_loja;
create policy linha_branca_lavadora_retornos_select
  on public.linha_branca_lavadora_retornos_loja for select to authenticated
  using (true);

grant select on public.linha_branca_lavadora_retornos_loja to authenticated;
grant usage, select on sequence public.linha_branca_lavadora_retornos_loja_id_seq to authenticated;

alter table public.linha_branca_lavadora_ciclos
  add column if not exists retorno_loja_id bigint references public.linha_branca_lavadora_retornos_loja(id) on delete set null;
alter table public.linha_branca_lavadora_eventos
  add column if not exists retorno_loja_id bigint references public.linha_branca_lavadora_retornos_loja(id) on delete set null;
alter table public.linha_branca_triagens
  add column if not exists retorno_loja_id bigint references public.linha_branca_lavadora_retornos_loja(id) on delete set null;
alter table public.ordens_servico_execucao
  add column if not exists retorno_loja_id bigint references public.linha_branca_lavadora_retornos_loja(id) on delete set null;
alter table public.linha_branca_lavadora_laudos
  add column if not exists retorno_loja_id bigint references public.linha_branca_lavadora_retornos_loja(id) on delete set null;

create or replace function public.linha_branca_vincular_retorno_ativo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.retorno_loja_id is null and new.os_id is not null then
    select r.id into new.retorno_loja_id
    from public.linha_branca_lavadora_retornos_loja r
    where r.os_id = new.os_id and r.status = 'aberto'
    order by r.numero_retorno desc
    limit 1;
  end if;
  return new;
end;
$$;

do $$
declare v_tabela text;
begin
  foreach v_tabela in array array[
    'linha_branca_lavadora_ciclos',
    'linha_branca_lavadora_eventos',
    'linha_branca_triagens',
    'ordens_servico_execucao',
    'linha_branca_lavadora_laudos'
  ] loop
    execute format('drop trigger if exists trg_vincular_retorno_ativo on public.%I', v_tabela);
    execute format(
      'create trigger trg_vincular_retorno_ativo before insert on public.%I for each row execute function public.linha_branca_vincular_retorno_ativo()',
      v_tabela
    );
  end loop;
end;
$$;

create or replace function public.linha_branca_abrir_retorno_loja(
  p_numero_os text,
  p_motivo text,
  p_observacoes text default null,
  p_operador text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_os public.ordens_servico;
  v_retorno public.linha_branca_lavadora_retornos_loja;
  v_numero integer;
  v_ja_existia boolean := true;
begin
  if auth.uid() is null then raise exception 'Usuário não autenticado.'; end if;
  if trim(coalesce(p_numero_os, '')) !~ '^[0-9]{5,10}$' then raise exception 'Número de OS inválido.'; end if;
  if nullif(trim(coalesce(p_motivo, '')), '') is null then raise exception 'Informe o motivo do retorno.'; end if;

  select * into v_os
  from public.ordens_servico
  where numero_os = trim(p_numero_os)
  for update;

  if not found then
    v_ja_existia := false;
    insert into public.ordens_servico (
      numero_os, dt_entrada, linha_produto, categoria, status_atual,
      etapa_atual, area_destino, origem, areas_reparo, areas_concluidas, criado_por
    ) values (
      trim(p_numero_os), current_date, 'Linha Branca', 'Lavadora', 'Aguardando triagem',
      'Aguardando triagem', null, 'Retorno de Loja', array[]::text[], array[]::text[],
      coalesce(nullif(trim(p_operador), ''), 'Retorno de Loja')
    ) returning * into v_os;
  end if;

  -- Protege contra duplo clique/reenvio da mesma solicitação.
  select * into v_retorno
  from public.linha_branca_lavadora_retornos_loja
  where os_id = v_os.id
    and status = 'aberto'
    and recebido_em >= now() - interval '2 minutes'
    and coalesce(recebido_por, '') = coalesce(nullif(trim(p_operador), ''), '')
    and motivo = trim(p_motivo)
  order by numero_retorno desc
  limit 1;

  if found then
    return to_jsonb(v_os) || jsonb_build_object(
      'retorno_loja_id', v_retorno.id,
      'numero_retorno', v_retorno.numero_retorno,
      'novo_retorno', false,
      'ja_existia', v_ja_existia
    );
  end if;

  update public.linha_branca_lavadora_retornos_loja
  set status = 'encerrado_por_novo_retorno', finalizado_em = now(), updated_at = now()
  where os_id = v_os.id and status = 'aberto';

  select coalesce(max(numero_retorno), 0) + 1 into v_numero
  from public.linha_branca_lavadora_retornos_loja
  where os_id = v_os.id;

  insert into public.linha_branca_lavadora_retornos_loja (
    os_id, numero_retorno, motivo, observacoes, recebido_por, recebido_por_id, snapshot_anterior
  ) values (
    v_os.id, v_numero, trim(p_motivo), nullif(trim(coalesce(p_observacoes, '')), ''),
    nullif(trim(coalesce(p_operador, '')), ''), auth.uid(), to_jsonb(v_os)
  ) returning * into v_retorno;

  update public.ordens_servico
  set
    status_atual = 'Aguardando triagem',
    etapa_atual = 'Aguardando triagem',
    area_destino = null,
    areas_reparo = array[]::text[],
    areas_concluidas = array[]::text[],
    origem = 'Retorno de Loja',
    tecnico_triagem = null,
    tecnico_bancada = null,
    tecnico_responsavel = null,
    aprovado_bancada = false,
    obs_bancada = null,
    updated_at = now()
  where id = v_os.id
  returning * into v_os;

  return to_jsonb(v_os) || jsonb_build_object(
    'retorno_loja_id', v_retorno.id,
    'numero_retorno', v_retorno.numero_retorno,
    'novo_retorno', true,
    'ja_existia', v_ja_existia
  );
end;
$$;

revoke all on function public.linha_branca_abrir_retorno_loja(text,text,text,text) from public, anon;
grant execute on function public.linha_branca_abrir_retorno_loja(text,text,text,text) to authenticated;

-- Um retorno de loja em andamento prevalece sobre a etapa antiga do Aging.
create or replace function public.linha_branca_aplicar_etapa_cmp()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.linha_produto = 'Linha Branca'
     and coalesce(new.origem, '') <> 'Retorno de Loja'
     and upper(trim(coalesce(new.dados_aging ->> 'ETAPA', ''))) ~
       '^AGUARDANDO( CONFIRMAÇÃO DE MOVIMENTAÇÃO)? CMP(/HF)?$' then
    new.status_atual := 'Aguardando peça';
    new.etapa_atual := 'Reparo';
    if new.area_destino is null or new.area_destino in ('Recebido', 'Aguardando triagem', 'Em triagem') then
      new.area_destino := 'Reparo Mecânico';
    end if;
    if coalesce(cardinality(new.areas_reparo), 0) = 0 then
      new.areas_reparo := array['Reparo Mecânico']::text[];
    end if;
  end if;
  return new;
end;
$$;

-- Recupera a tentativa já realizada pelo Kaua para a OS 570748.
-- O estado anterior fica congelado no snapshot e a máquina volta à triagem como Retorno #1.
with os_alvo as (
  select o.*
  from public.ordens_servico o
  where o.numero_os = '570748'
), retorno_criado as (
  insert into public.linha_branca_lavadora_retornos_loja (
    os_id, numero_retorno, motivo, observacoes, recebido_por, snapshot_anterior
  )
  select
    o.id,
    1,
    'Produto apresentou defeito após a venda e foi devolvido pelo cliente.',
    'Retorno de loja registrado originalmente pelo Kaua.',
    'Kaua',
    to_jsonb(o)
  from os_alvo o
  where not exists (
    select 1
    from public.linha_branca_lavadora_retornos_loja r
    where r.os_id = o.id
  )
  returning os_id
)
update public.ordens_servico o
set
  status_atual = 'Aguardando triagem',
  etapa_atual = 'Aguardando triagem',
  area_destino = null,
  areas_reparo = array[]::text[],
  areas_concluidas = array[]::text[],
  origem = 'Retorno de Loja',
  tecnico_triagem = null,
  tecnico_bancada = null,
  tecnico_responsavel = null,
  aprovado_bancada = false,
  obs_bancada = null,
  updated_at = now()
where o.id in (select os_id from retorno_criado);

